def png(path, width, height, depth=8, alpha=False, gray=False):
    def chunk(kind, payload):
        return struct.pack('>I', len(payload)) + kind + payload + struct.pack('>I', zlib.crc32(kind + payload))
    data = bytearray()
    for y in range(height):
        data.append(0)
        for x in range(width):
            channels = [(x * 255 // (width - 1)), (y * 255 // (height - 1)), (x ^ y) % 256]
            if gray:
                channels = [(channels[0] + channels[1] + channels[2]) // 3]
            if alpha:
                channels.append((x + y) * 255 // (width + height - 2))
            for value in channels:
                data.extend(struct.pack('>H', value * 257) if depth == 16 else bytes([value]))
    path.write_bytes(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, depth, (4 if alpha else 0) if gray else (6 if alpha else 2), 0, 0, 0))
                    + chunk(b'IDAT', zlib.compress(data)) + chunk(b'IEND', b''))


def box(kind, payload=b''):
    return struct.pack('>I', len(payload) + 8) + kind + payload


def full(kind, payload=b''):
    return box(kind, bytes(4) + payload)


def boxes(data):
    offset = 0
    while offset + 8 <= len(data):
        size, kind = struct.unpack_from('>I4s', data, offset)
        yield kind, data[offset + 8:offset + size]
        offset += size


def item_count(path):
    """Entry count of iinf (ISO/IEC 14496-12 8.11.6), the expected ImageInfo.ContainerItemCount."""
    meta = next(payload for kind, payload in boxes(path.read_bytes()) if kind == b'meta')
    iinf = next(payload for kind, payload in boxes(meta[4:]) if kind == b'iinf')
    return struct.unpack_from('>H' if iinf[0] == 0 else '>I', iinf, 4)[0]


def boxes(data):
    offset = 0
    while offset < len(data):
        length, kind = struct.unpack_from('>I4s', data, offset)
        if length < 8 or offset + length > len(data):
            raise ValueError('Invalid generated source box')
        yield kind, data[offset + 8:offset + length]
        offset += length


def grid(source, rotation=False):
    # A small independent container writer, using actual HEVC configuration/payload generated by heif-enc.
    top = dict(boxes(source))
    meta = dict(boxes(top[b'meta'][4:]))
    iprp = dict(boxes(meta[b'iprp']))
    config = dict(boxes(iprp[b'ipco']))[b'hvcC']
    image = top[b'mdat']
    u16 = lambda value: struct.pack('>H', value)
    u32 = lambda value: struct.pack('>I', value)
    ispe = lambda w, h: full(b'ispe', u32(w) + u32(h))
    # Tiles are hidden items (infe flags bit 0), so readers present only the grid as a top-level image.
    infe = lambda ident, kind, hidden=False: box(b'infe', (b'\x02\0\0\x01' if hidden else b'\x02\0\0\0') + u16(ident) + u16(0) + kind + b'\0')
    payload = bytes([0, 0, 0, 1]) + u16(120) + u16(64)
    locations = b'\x44\0' + u16(3)
    for ident, offset, length in [(1, 0, 8), (2, 8, len(image)), (3, 8, len(image))]:
        locations += u16(ident) + u16(1) + u16(0) + u16(1) + u32(offset) + u32(length)
    properties = ispe(120, 64) + ispe(64, 64) + box(b'hvcC', config)
    primary_associations = bytes([1, 0x84, 0x85]) if rotation else bytes([1])
    if rotation:
        properties += box(b'irot', b'\x01') + box(b'imir', b'\x00')
    associations = u32(3) + u16(1) + bytes([len(primary_associations)]) + primary_associations
    associations += u16(2) + bytes([2, 2, 0x83]) + u16(3) + bytes([2, 2, 0x83])
    container = full(b'hdlr', u32(0) + b'pict' + bytes(12) + b'\0') + full(b'pitm', u16(1))
    container += full(b'iinf', u16(3) + infe(1, b'grid') + infe(2, b'hvc1', True) + infe(3, b'hvc1', True))
    container += box(b'iloc', b'\x01\0\0\0' + locations)
    container += box(b'iprp', box(b'ipco', properties) + full(b'ipma', associations))
    container += full(b'iref', box(b'dimg', u16(1) + u16(2) + u16(2) + u16(3)))
    container += box(b'idat', payload + image)
    return box(b'ftyp', b'heic' + u32(0) + b'mif1heic') + full(b'meta', container)


def read_png(path):
    """Minimal PNG reader (non-interlaced, 8/16-bit gray, gray+alpha, RGB, RGBA) for heif-dec output."""
    data = path.read_bytes()
    position, chunks, header = 8, b'', None
    while position < len(data):
        length, kind = struct.unpack_from('>I4s', data, position)
        body = data[position + 8:position + 8 + length]
        position += 12 + length
        if kind == b'IHDR':
            header = struct.unpack('>IIBBBBB', body)
        elif kind == b'IDAT':
            chunks += body
    width, height, depth, colour_type = header[:4]
    channels = {0: 1, 2: 3, 4: 2, 6: 4}[colour_type]
    bpp = channels * depth // 8
    raw = zlib.decompress(chunks)
    rows, previous, offset = [], bytearray(width * bpp), 0
    for _ in range(height):
        kind, line = raw[offset], bytearray(raw[offset + 1:offset + 1 + width * bpp])
        offset += 1 + width * bpp
        for i in range(len(line)):
            a = line[i - bpp] if i >= bpp else 0
            b = previous[i]
            c = previous[i - bpp] if i >= bpp else 0
            if kind == 1:
                line[i] = (line[i] + a) & 255
            elif kind == 2:
                line[i] = (line[i] + b) & 255
            elif kind == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif kind == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(bytes(line))
        previous = line
    samples = []
    for line in rows:
        if depth == 16:
            samples.append([(line[i] << 8) | line[i + 1] for i in range(0, len(line), 2)])
        else:
            samples.append(list(line))
    return width, height, channels, depth, samples


def rgba_reference(path, premultiplied, bits):
    """SHA-256 of heif-dec's output as 8-bit straight RGBA, using PictureSharp.Heif's documented reductions:
    10-bit samples (stored as v << 6 in 16-bit PNG) become round(v * 255 / 1023); premultiplied colour is divided by
    alpha like PictureSharp's ToStraight."""
    with tempfile.TemporaryDirectory(prefix='heif-rgba-') as temporary:
        output = Path(temporary) / 'out.png'
        subprocess.run([str(TOOLS / 'bin/heif-dec'), '--quiet', str(path), str(output)], check=True, stdout=subprocess.PIPE)
        width, height, channels, depth, samples = read_png(output)
    maximum = (1 << bits) - 1
    pixels = bytearray()
    for row in samples:
        for x in range(width):
            values = row[x * channels:(x + 1) * channels]
            if depth == 16:
                values = [((v >> (16 - bits)) * 255 + maximum // 2) // maximum for v in values]
            if channels in (1, 2):
                values = [values[0]] * 3 + values[1:]
            if len(values) == 3:
                values.append(255)
            r, g, b, a = values
            if premultiplied and a not in (0, 255):
                r, g, b = min(255, 255 * r // a), min(255, 255 * g // a), min(255, 255 * b // a)
            pixels += bytes([r, g, b, a])
    return width, height, hashlib.sha256(pixels).hexdigest()


def exif_orientation(value):
    # HEIF Exif item: exif_tiff_header_offset (0) followed by a big-endian TIFF with one Orientation tag.
    ifd = struct.pack('>H', 1) + struct.pack('>HHIHH', 0x0112, 3, 1, value, 0) + struct.pack('>I', 0)
    return struct.pack('>I', 0) + b'MM\0*' + struct.pack('>I', 8) + ifd


XMP = (b'<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
       b'<rdf:Description xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:title>PictureSharp.Heif corpus</dc:title>'
       b'</rdf:Description></rdf:RDF></x:xmpmeta>')


def wrap(source, colr=b'keep', transforms=(), exif=None, xmp=None):
    """Independent single-image container around a heif-enc payload: chosen colr box (b'keep', None or box bytes),
    transform properties in the given association order, and optional Exif/XMP items linked with cdsc."""
    top = dict(boxes(source))
    meta = dict(boxes(top[b'meta'][4:]))
    ipco = list(boxes(dict(boxes(meta[b'iprp']))[b'ipco']))
    config = next(p for k, p in ipco if k == b'hvcC')
    spatial = next(p for k, p in ipco if k == b'ispe')
    original = next((p for k, p in ipco if k == b'colr'), None)
    image = top[b'mdat']
    u16 = lambda value: struct.pack('>H', value)
    u32 = lambda value: struct.pack('>I', value)
    properties = [box(b'ispe', spatial), box(b'hvcC', config)]
    if colr == b'keep' and original is not None:
        properties.append(box(b'colr', original))
    elif colr not in (b'keep', None):
        properties.append(box(b'colr', colr))
    properties += [box(kind, value) for kind, value in transforms]
    associations = bytes([len(properties)]) + bytes([0x80 | 2] + [i + 1 for i in range(len(properties)) if i != 1])
    entries = [(1, b'hvc1', image, b'')]
    if exif is not None:
        entries.append((2, b'Exif', exif, b''))
    if xmp is not None:
        entries.append((3, b'mime', xmp, b'application/rdf+xml\0'))
    infos = b''.join(box(b'infe', b'\x02\0\0\0' + u16(i) + u16(0) + kind + b'\0' + extra) for i, kind, _, extra in entries)
    locations = b'\x44\0' + u16(len(entries))
    offset = 0
    for i, _, data, _ in entries:
        locations += u16(i) + u16(1) + u16(0) + u16(1) + u32(offset) + u32(len(data))
        offset += len(data)
    references = b''.join(box(b'cdsc', u16(i) + u16(1) + u16(1)) for i, _, _, _ in entries[1:])
    container = full(b'hdlr', u32(0) + b'pict' + bytes(12) + b'\0') + full(b'pitm', u16(1))
    container += full(b'iinf', u16(len(entries)) + infos)
    container += box(b'iloc', b'\x01\0\0\0' + locations)
    container += box(b'iprp', box(b'ipco', b''.join(properties)) + full(b'ipma', u32(1) + u16(1) + associations))
    if references:
        container += full(b'iref', references)
    container += box(b'idat', b''.join(data for _, _, data, _ in entries))
    return box(b'ftyp', b'heic' + u32(0) + b'mif1heic') + full(b'meta', container)


APPLE_MAP_XMP = (b'<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
                 b'<rdf:Description xmlns:HDRGainMap="http://ns.apple.com/HDRGainMap/1.0/" HDRGainMap:HDRGainMapVersion="131072"'
                 b' HDRGainMap:HDRGainMapHeadroom="3.5"/></rdf:RDF></x:xmpmeta>')


def apple_exif():
    """HEIF Exif item with an Apple MakerNote (tags 33 = 1.2 and 48 = 0.5, headroom 2^(2.303 - 0.303 * 0.5)), which
    takes precedence over the map's XMP headroom. Big-endian TIFF: IFD0 -> Exif IFD -> MakerNote."""
    note = b'Apple iOS\0' + struct.pack('>H', 1) + b'MM'
    note += struct.pack('>H', 2) + struct.pack('>HHII', 33, 10, 1, 44) + struct.pack('>HHII', 48, 10, 1, 52) + struct.pack('>I', 0)
    note += struct.pack('>iI', 12, 10) + struct.pack('>iI', 1, 2)
    ifd0 = struct.pack('>H', 1) + struct.pack('>HHII', 0x8769, 4, 1, 26) + struct.pack('>I', 0)      # at 8, Exif IFD at 26
    exif_ifd = struct.pack('>H', 1) + struct.pack('>HHII', 0x927C, 7, len(note), 44) + struct.pack('>I', 0)  # at 26
    return struct.pack('>I', 0) + b'MM\0*' + struct.pack('>I', 8) + ifd0 + exif_ifd + note


def rational(value):
    return round(value * 1000000), 1000000


def iso_payload(channels, alternate_headroom, maxima, gamma=1.0, offset=1 / 64):
    """ISO 21496-1 metadata (minimum and writer version 0, base colour space, SDR base) with per-fraction denominators."""
    flags = (0x80 if channels == 3 else 0) | 0x40
    data = struct.pack('>HHB', 0, 0, flags) + struct.pack('>II', 0, 1) + struct.pack('>II', *rational(alternate_headroom))
    for channel in range(channels):
        data += struct.pack('>iI', 0, 1) + struct.pack('>iI', *rational(maxima[channel])) + struct.pack('>II', *rational(gamma))
        data += struct.pack('>iI', *rational(offset)) + struct.pack('>iI', *rational(offset))
    return data


def gain_map_file(base, gain, kind, rotated=False, iso=None, exif=None, tmap_version=0):
    """Independent container with a base image and an HDR gain map from heif-enc payloads. kind 'apple': an auxiliary
    image urn:com:apple:photo:2020:aux:hdrgainmap with its XMP; 'iso': a hidden map and a tmap item (version byte and
    ISO 21496-1 metadata) deriving from the base and the map, grouped with the base in altr; 'both': one map with both
    descriptions, as iPhones write since iOS 18. rotated adds irot 1 to the base, the map and the tmap item."""
    def parts(source):
        top = dict(boxes(source))
        ipco = list(boxes(dict(boxes(dict(boxes(top[b'meta'][4:]))[b'iprp']))[b'ipco']))
        get = lambda name: next((value for key, value in ipco if key == name), None)
        return get(b'ispe'), get(b'hvcC'), get(b'colr'), top[b'mdat'], get(b'clap')
    u16 = lambda value: struct.pack('>H', value)
    u32 = lambda value: struct.pack('>I', value)
    properties = []

    def prop(name, payload):
        properties.append(box(name, payload))
        return len(properties)
    rotation = prop(b'irot', b'\x01') if rotated else None
    apple = kind in ('apple', 'both')
    with_iso = kind in ('iso', 'both')
    associations = {}
    for ident, source in [(1, base), (2, gain)]:
        spatial, config, colour, _, aperture = parts(source)
        indexes = [prop(b'ispe', spatial), 0x80 | prop(b'hvcC', config)]
        if colour is not None:
            indexes.append(prop(b'colr', colour))
        if aperture is not None:
            # heif-enc codes whole CTUs and crops to the source size.
            indexes.append(0x80 | prop(b'clap', aperture))
        if ident == 2 and apple:
            indexes.append(prop(b'auxC', bytes(4) + b'urn:com:apple:photo:2020:aux:hdrgainmap\0'))
        if rotation:
            indexes.append(rotation)
        associations[ident] = indexes
    entries = [(1, b'hvc1', parts(base)[3], b'', False), (2, b'hvc1', parts(gain)[3], b'', not apple)]
    references = []
    if with_iso:
        associations[3] = [prop(b'ispe', struct.pack('>4xII', 64, 48))] + ([rotation] if rotation else [])
        entries.append((3, b'tmap', bytes([tmap_version]) + iso, b'', False))
        references.append(box(b'dimg', u16(3) + u16(2) + u16(1) + u16(2)))
    if apple:
        references.append(box(b'auxl', u16(2) + u16(1) + u16(1)))
    if exif is not None:
        entries.append((4, b'Exif', exif, b'', False))
        references.append(box(b'cdsc', u16(4) + u16(1) + u16(1)))
    if apple:
        entries.append((5, b'mime', APPLE_MAP_XMP, b'application/rdf+xml\0', False))
        references.append(box(b'cdsc', u16(5) + u16(1) + u16(2)))
    infos = b''.join(box(b'infe', (b'\x02\0\0\x01' if hidden else b'\x02\0\0\0') + u16(i) + u16(0) + name + b'\0' + extra)
                     for i, name, _, extra, hidden in entries)
    locations = b'\x44\0' + u16(len(entries))
    offset = 0
    for i, _, data, _, _ in entries:
        locations += u16(i) + u16(1) + u16(0) + u16(1) + u32(offset) + u32(len(data))
        offset += len(data)
    ipma = u32(len(associations)) + b''.join(u16(i) + bytes([len(v)]) + bytes(v) for i, v in sorted(associations.items()))
    container = full(b'hdlr', u32(0) + b'pict' + bytes(12) + b'\0') + full(b'pitm', u16(1))
    container += full(b'iinf', u16(len(entries)) + infos)
    container += box(b'iloc', b'\x01\0\0\0' + locations)
    container += box(b'iprp', box(b'ipco', b''.join(properties)) + full(b'ipma', ipma))
    container += full(b'iref', b''.join(references))
    if with_iso:
        container += box(b'grpl', full(b'altr', u32(100) + u32(2) + u32(3) + u32(1)))
    container += box(b'idat', b''.join(data for _, _, data, _, _ in entries))
    brands = b'mif1heic' + (b'tmap' if with_iso else b'')
    return box(b'ftyp', b'heic' + u32(0) + brands) + full(b'meta', container)


