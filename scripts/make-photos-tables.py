#!/usr/bin/env python3
"""Generate src/PictureSharp.Heif/Codecs/HeifPhotosTables.cs from the fitted Photos adjustment parameters.

Usage: scripts/make-photos-tables.py [docs/measurements/photos-edits-0.6.8]

Reads <prefix>-select.tsv (chosen model per adjustment) and <prefix>-curves.tsv (parameters per scene and slider
value, written by scripts/fit-photos-edits.py). Parameters of the same adjustment and value are averaged over the
scenes that have them. Every slider value gets one record of RecordLength floats:
  [0, 99)    channel curve deltas R, G, B at 33 knots (8-bit sRGB; a shared curve is repeated per channel)
  [99, 132)  luma curve delta at 33 knots (added to all channels, or the luma part of a chroma model)
  [132, 165) chroma gain - 1 at 33 knots of saturation (max - min) / max
  [165, 173) gains of the Gaussian bands sigma 1, 2, 4, ..., 128
  [173, 206) log gain (linear light) at 33 knots of the normalised radius
"""
import csv, os, sys
from collections import defaultdict

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
prefix = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, 'docs/measurements/photos-edits-0.6.8')
OUT = os.path.join(REPO, 'src/PictureSharp.Heif/Codecs/HeifPhotosTables.cs')
ORDER = ['exposure', 'brilliance', 'highlights', 'shadows', 'contrast', 'brightness', 'black_point', 'saturation',
         'vibrance', 'warmth', 'tint', 'sharpness', 'definition', 'noise_reduction', 'vignette']
SIGMAS = [1, 2, 4, 8, 16, 32, 64, 128]


def rows(path):
    with open(path) as f:
        return list(csv.DictReader([l for l in f if not l.startswith('#')], delimiter='\t'))


model = {r['adjustment']: r['chosen'] for r in rows(prefix + '-select.tsv')}
params = defaultdict(lambda: defaultdict(dict))  # adj -> value -> scene -> param -> list
for r in rows(prefix + '-curves.tsv'):
    params[r['adjustment']][int(r['value'])].setdefault(r['scene'], defaultdict(list))[r['param']].append(float(r['y']))


def record(adj, scenes):
    m = model[adj]
    rec = [0.0] * 206
    for sc in scenes.values():
        k = 1 / len(scenes)
        if 'd_r' in sc:
            for c, name in enumerate(('d_r', 'd_g', 'd_b')):
                for i, y in enumerate(sc[name]):
                    rec[c * 33 + i] += k * y
        elif m in ('curve_rgb', 'curve_rgb_bands'):
            for c in range(3):
                for i, y in enumerate(sc['d']):
                    rec[c * 33 + i] += k * y
        elif 'd' in sc:  # luma_add, chroma_srgb
            for i, y in enumerate(sc['d']):
                rec[99 + i] += k * y
        for i, y in enumerate(sc.get('g', [])):
            rec[132 + i] += k * y
        for i, s in enumerate(SIGMAS):
            if f'band_{s}' in sc:
                rec[165 + i] += k * sc[f'band_{s}'][0]
        for i, y in enumerate(sc.get('lg', [])):
            rec[173 + i] += k * y
    return rec


lines = []
for adj in ORDER:
    name = ''.join(w.capitalize() for w in adj.split('_'))
    values = sorted(params[adj])
    scenes = sorted({s for v in values for s in params[adj][v]})
    lines.append(f'    // {adj}: {model[adj]}, scenes {", ".join(scenes)}')
    lines.append(f'    public static ReadOnlySpan<float> {name}Values => [{", ".join(f"{v}f" for v in values)}];')
    lines.append(f'    public static ReadOnlySpan<float> {name} =>')
    lines.append('    [')
    for v in values:
        rec = record(adj, params[adj][v])
        for i in range(0, len(rec), 11):
            lines.append('        ' + ', '.join(f'{x:.5g}f' for x in rec[i:i + 11]) + ',')
    lines.append('    ];')
    lines.append('')

with open(OUT, 'w') as f:
    f.write('''// <auto-generated>
// Generated by scripts/make-photos-tables.py from docs/measurements/photos-edits-0.6.8-curves.tsv; do not edit.
// </auto-generated>

namespace PictureSharp.Formats.Heif.Codecs;

// Fitted Photos adjustment parameters per slider value (layout in HeifPhotosRenderer), averaged over the scenes.
internal static class HeifPhotosTables
{
    public const int RecordLength = 206;

''' + '\n'.join(lines).rstrip() + '\n}\n')
print('written', OUT)
